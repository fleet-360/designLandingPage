# new items: (clause, sub item)
ADDED = [
    ("5.4", {"n": "ג", "text": "כרטיס אשראי: לקראת מועד התשלום תשלח החברה ללקוח קישור מאובטח לתשלום, והסכום ישולם עד התאריך הנקוב."}),
]


def find(ref):
    n, _, sub = ref.partition("/")
    for s in doc["sections"]:
        for c in s["clauses"]:
            if c["n"] == n:
                if not sub:
                    return c
                for x in c["sub"]:
                    if x["n"] == sub:
                        return x
    raise SystemExit(f"clause {ref} not found")


for ref, old, new in CHANGES:
    node = find(ref)
    assert node["text"].count(old) == 1, f"{ref}: text not found exactly once"
    node["text"] = node["text"].replace(old, new)
for ref, item in ADDED:
    clause = find(ref)
    assert all(x["n"] != item["n"] for x in clause["sub"]), f"{ref}/{item['n']} exists"
    clause["sub"].append(item)

head = ("// Generated by tools/sales/agreement_v3_from_v2.py: agreement-v2.js with the changes listed there.\n"
        "// Do not edit by hand. Keep it for deals already sent once a v4 exists.\n")
out = head + "export const AGREEMENT = " + json.dumps(doc, ensure_ascii=False, indent=2) + ";\n"
(ROOT / "api/_lib/agreement-v3.js").write_text(out, encoding="utf-8")
print("api/_lib/agreement-v3.js:", len(CHANGES), "changes,", len(ADDED), "added")
