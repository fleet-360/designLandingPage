"""Converts the framework agreement (Word) into api/_lib/agreement-v1.js, once per agreement version.

The legal text is copied as is: sections ("1. title"), clauses ("1.1 text") and sub-clauses ("(a) text").
The parties block, the work order page and Appendix A are built from each deal's data and are not
taken from the file. Run: python tools/sales/agreement_from_docx.py <file.docx> <version>
"""
import json, re, sys
import docx

src, version = sys.argv[1], sys.argv[2]
paras = [p.text.strip() for p in docx.Document(src).paragraphs if p.text.strip()]
start = paras.index("הסכם מסגרת לפיתוח תוכנה")
end = next(i for i, p in enumerate(paras) if p.startswith("ולראיה באו הצדדים"))
body = paras[start:end]

recitals, sections = [], []
for p in body[2:]:
    if p.startswith("הואיל") or p.startswith("והואיל") or p.startswith("לפיכך"):
        recitals.append(p)
        continue
    if p in ("הצדדים",) or p.startswith("בין:") or p.startswith("לבין:") or p.startswith("כתובת הלקוח"):
        continue
    m = re.match(r"^(\d+)\.\s+(.+)$", p)
    if m and not re.match(r"^\d+\.\d", p):
        sections.append({"n": int(m.group(1)), "title": m.group(2), "clauses": []})
        continue
    m = re.match(r"^(\d+\.\d+)\s+(.+)$", p)
    if m:
        sections[-1]["clauses"].append({"n": m.group(1), "text": m.group(2), "sub": []})
        continue
    m = re.match(r"^\(([א-ת])\)\s*(.+)$", p)
    if m:
        sections[-1]["clauses"][-1]["sub"].append({"n": m.group(1), "text": m.group(2)})
        continue
    if sections and sections[-1]["clauses"]:
        sections[-1]["clauses"][-1]["text"] += "\n" + p
    else:
        raise SystemExit(f"unplaced paragraph: {p[:60]}")

agreement = {
    "version": version,
    "title": body[0],
    "subtitle": body[1],
    "recitals": recitals,
    "sections": sections,
    "closing": "ולראיה באו הצדדים על החתום",
}
out = "// Generated by tools/sales/agreement_from_docx.py from the framework agreement (Word). Do not edit\n" \
      "// by hand: change the Word file, add a new version, and keep this one for deals already sent.\n" \
      f"export const AGREEMENT = {json.dumps(agreement, ensure_ascii=False, indent=2)};\n"
open(f"api/_lib/agreement-{version}.js", "w", encoding="utf-8", newline="\n").write(out)
print(version, len(sections), "sections,", sum(len(s["clauses"]) for s in sections), "clauses,", len(recitals), "recitals")
