def find(ref):
    n, _, sub = ref.partition("/")
    for s in doc["sections"]:
        for c in s["clauses"]:
            if c["n"] == n:
                if not sub:
                    return c
                for x in c["sub"]:
                    if x["n"] == sub:
                        return x
    raise SystemExit(f"clause {ref} not found")


for ref, old, new in CHANGES:
    node = find(ref)
    assert node["text"].count(old) == 1, f"{ref}: text not found exactly once"
    node["text"] = node["text"].replace(old, new)

